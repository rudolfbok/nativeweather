import type { NormalizedData, WeatherAPIResponse } from '@nativeweather/types';
import { normalizeWeatherConditionCode } from './utils/weatherCondition';

const mapCondition = (condition: { text?: unknown; code?: unknown } | null | undefined) => ({
	text: '',
	code: normalizeWeatherConditionCode(condition?.code),
});

export const mapWeatherApi = (data: WeatherAPIResponse): NormalizedData => {
	return {
		location: {
			name: data.location.name,
			region: data.location.region,
			country: data.location.country,
			lat: data.location.lat,
			lon: data.location.lon,
			localtimeEpoch: data.location.localtime_epoch,
			tzId: data.location.tz_id,
		},
		current: {
			tempC: data.current.temp_c,
			tempF: data.current.temp_f,
			feelsLikeC: data.current.feelslike_c,
			feelsLikeF: data.current.feelslike_f,
			dewPointC: data.current.dewpoint_c,
			dewPointF: data.current.dewpoint_f,
			humidity: data.current.humidity,
			precipIn: data.current.precip_in,
			precipMm: data.current.precip_mm,
			pressureInHg: data.current.pressure_in,
			pressureMb: data.current.pressure_mb,
			uv: data.current.uv,
			rangeKm: data.current.vis_km,
			rangeMiles: data.current.vis_miles,
			windDegree: data.current.wind_degree,
			windDir: data.current.wind_dir,
			windKph: data.current.wind_kph,
			windMph: data.current.wind_mph,
			gustKph: data.current.gust_kph,
			gustMph: data.current.gust_mph,
			cloudCover: data.current.cloud,
			isDay: data.current.is_day,
			condition: mapCondition(data.current.condition),
		},
		forecast: {
			forecastday: data.forecast.forecastday.map((day) => ({
				date: day.date,
				date_epoch: day.date_epoch,
				day: {
					maxTempC: day.day.maxtemp_c,
					maxTempF: day.day.maxtemp_f,
					minTempC: day.day.mintemp_c,
					minTempF: day.day.mintemp_f,
					maxWindKph: day.day.maxwind_kph,
					maxWindMph: day.day.maxwind_mph,
					dailyRainChance: day.day.daily_chance_of_rain,
					dailySnowChance: day.day.daily_chance_of_snow,
					dailyWillItSnow: day.day.daily_will_it_snow,
					uv: day.day.uv,
					avgVisKm: day.day.avgvis_km,
					avgVisMiles: day.day.avgvis_miles,
					avgHumidity: day.day.avghumidity,
					totalPrecipMm: day.day.totalprecip_mm,
					totalPrecipIn: day.day.totalprecip_in,
					totalSnowCm: day.day.totalsnow_cm,
					condition: mapCondition(day.day.condition),
				},
				hour: day.hour.map((hour) => ({
					timeEpoch: hour.time_epoch,
					time: hour.time,
					tempC: hour.temp_c,
					tempF: hour.temp_f,
					isDay: hour.is_day,
					uv: hour.uv,
					chanceOfRain: hour.chance_of_rain,
					chanceOfSnow: hour.chance_of_snow,
					snowCm: hour.snow_cm,
					precipMm: hour.precip_mm,
					humidity: hour.humidity,
					pressureMb: hour.pressure_mb,
					pressureInHg: hour.pressure_in,
					rangeKm: hour.vis_km,
					rangeMiles: hour.vis_miles,
					windKph: hour.wind_kph,
					windMph: hour.wind_mph,
					condition: mapCondition(hour.condition),
				})),
				astro: {
					sunrise: day.astro.sunrise,
					sunset: day.astro.sunset,
					moonPhase: day.astro.moon_phase,
					moonIllumination: day.astro.moon_illumination,
					moonRise: day.astro.moonrise,
					moonSet: day.astro.moonset,
					isMoonUp: day.astro.is_moon_up,
				},
			})),
		},
		alerts: {
			alert: data.alerts?.alert ?? [],
		},
	};
};
